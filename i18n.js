  let lang;
  try { lang = localStorage.getItem(LANG_KEY); } catch (e) {}
  if (lang !== "ar" && lang !== "en") lang = CFG.DEFAULT_LANG === "en" ? "en" : "ar";

  const toArabicDigits = (s) => String(s).replace(/\d/g, (d) => "٠١٢٣٤٥٦٧٨٩"[d]);

  function t(key, vars) {
    let s = (S[lang] && S[lang][key]) || S.en[key] || key;
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(lang === "ar" && typeof vars[k] === "number" ? toArabicDigits(vars[k]) : vars[k]);
    return names(s);
  }
  // Fill in the couple's first names.
  function names(s) {
    const N = CFG.NAMES || {};
    return String(s).split("{g}").join((N.groom && N.groom[lang]) || (lang === "ar" ? "العريس" : "the groom"))
      .split("{b}").join((N.bride && N.bride[lang]) || (lang === "ar" ? "العروسة" : "the bride"));
  }
  const qText = (q) => names(q[lang] || q.en);

  function applyLang() {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t); });
    document.querySelectorAll("[data-tph]").forEach((el) => { el.placeholder = t(el.dataset.tph); });
    document.querySelectorAll("[data-couple]").forEach((el) => { el.textContent = (CFG.COUPLE && CFG.COUPLE[lang]) || ""; });
  }

  function setLang(l) {
    lang = l;
    try { localStorage.setItem(LANG_KEY, l); } catch (e) {}
    applyLang();
    document.dispatchEvent(new CustomEvent("langchange"));
  }

